async def phase_c(conn: asyncpg.Connection, commit: bool, ts: str) -> dict:
    print("\n" + "=" * 70)
    print("PHASE C — drop bogus Topica/Orator works")
    print("=" * 70)

    result: dict = {}
    for canon, label in ((TOPICA_CANONICAL, "Topica"), (ORATOR_CANONICAL, "Orator")):
        wid = await _work_id(conn, canon)
        if wid is None:
            print(f"  {label} ({canon}): already absent.")
            result[label] = {"present": False}
            continue
        n_pass = await conn.fetchval(
            "SELECT count(*) FROM free_will.passages WHERE work_id = $1::uuid", wid
        )
        n_cit = await conn.fetchval(
            "SELECT count(*) FROM free_will.passage_citations pc "
            "JOIN free_will.passages p ON p.passage_id = pc.passage_id "
            "WHERE p.work_id = $1::uuid",
            wid,
        )
        print(f"  {label} ({canon}): passages={n_pass}, remaining citations={n_cit}")
        if n_cit != 0:
            raise SystemExit(
                f"STOP: {label} ({canon}) still has {n_cit} passage_citations. "
                "Run Phase A + B first. Refusing to delete a work with live citations."
            )
        result[label] = {
            "present": True,
            "passages": n_pass,
            "remaining_citations": n_cit,
            "work_id": wid,
        }

    (SNAPSHOT_DIR / "phase_c.json").write_text(
        json.dumps(
            {"timestamp": ts, "phase": "C", "works": result},
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    if commit:
        async with conn.transaction():
            for label, info in result.items():
                if not info.get("present"):
                    continue
                wid = info["work_id"]
                await conn.execute(
                    "DELETE FROM free_will.passages WHERE work_id = $1::uuid", wid
                )
                await conn.execute(
                    "DELETE FROM free_will.ancient_works WHERE work_id = $1::uuid", wid
                )
                print(
                    f"  COMMITTED: deleted {label} ({info['passages']} passages + 1 work row)."
                )
    else:
        print("[DRY-RUN] Phase C: no DB changes.")

    return result


async def main(phase: str, commit: bool) -> int:
    import asyncpg

    SNAPSHOT_DIR.mkdir(parents=True, exist_ok=True)
    ts = _stamp()
    print(f"Mode: {'COMMIT' if commit else 'DRY-RUN'}   Phase: {phase}   {ts}")

    conn = await asyncio.wait_for(asyncpg.connect(_pg_url(_db_url())), timeout=30)
    try:
        if phase in ("A", "all"):
            await phase_a(conn, commit, ts)
        if phase in ("B", "all"):
            await phase_b(conn, commit, ts)
        if phase in ("C", "all"):
            await phase_c(conn, commit, ts)
    finally:
        await conn.close()
    if not commit:
        print("\n[DRY-RUN] Pass --commit to apply.")
    return 0


