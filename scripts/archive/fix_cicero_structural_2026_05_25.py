async def phase_b(conn: asyncpg.Connection, commit: bool, ts: str) -> dict:
    print("\n" + "=" * 70)
    print("PHASE B — delete fake passage-shells (DB + git mirror)")
    print("=" * 70)

    shells = await _shell_ids(conn)
    print(f"Shell nodes (DB): {len(shells)}")

    # Confirm no argument still depends on a shell via a non-structural relation
    # other than the cites_primary_source / evidenced_by we are about to delete.
    dep = await conn.fetch(
        "SELECT relation, count(*) c FROM free_will.kg_edges "
        "WHERE (source = ANY($1::text[]) OR target = ANY($1::text[])) "
        "GROUP BY relation ORDER BY relation",
        shells,
    )
    print("Shell edge relations (DB):")
    for d in dep:
        print(f"  {d['relation']}: {d['c']}")

    cit_n = await conn.fetchval(
        "SELECT count(*) FROM free_will.passage_citations WHERE kg_node_id = ANY($1::text[])",
        shells,
    )
    edge_n = await conn.fetchval(
        "SELECT count(*) FROM free_will.kg_edges WHERE source = ANY($1::text[]) OR target = ANY($1::text[])",
        shells,
    )
    print(
        f"\nDB to delete: passage_citations={cit_n}, kg_edges={edge_n}, kg_nodes={len(shells)}"
    )

    # Snapshot the exact rows
    cit_rows = [
        dict(r)
        for r in await conn.fetch(
            "SELECT citation_id::text, passage_id::text, kg_node_id, citation_type, confidence "
            "FROM free_will.passage_citations WHERE kg_node_id = ANY($1::text[])",
            shells,
        )
    ]
    edge_rows = [
        dict(r)
        for r in await conn.fetch(
            "SELECT edge_id::text, source, target, relation "
            "FROM free_will.kg_edges WHERE source = ANY($1::text[]) OR target = ANY($1::text[])",
            shells,
        )
    ]
    node_rows = [
        dict(r)
        for r in await conn.fetch(
            "SELECT node_id, id, label, type FROM free_will.kg_nodes WHERE node_id = ANY($1::text[])",
            shells,
        )
    ]
    (SNAPSHOT_DIR / "phase_b.json").write_text(
        json.dumps(
            {
                "timestamp": ts,
                "phase": "B",
                "shells": shells,
                "deleted_citations": cit_rows,
                "deleted_edges": edge_rows,
                "deleted_nodes": node_rows,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    # git mirror counts (dry-run preview = same predicate, commit=False)
    shell_set = set(shells)
    git_nodes_dropped = _remove_git_lines(
        NODES_PATH, lambda o: _git_node_id(o) in shell_set, commit
    )

    def _edge_touches_shell(o: dict) -> bool:
        s, t, _r = _git_edge_ends(o)
        return s in shell_set or t in shell_set

    git_edges_dropped = _remove_git_lines(
        EDGES_PATH,
        _edge_touches_shell,
        commit,
    )
    print(
        f"git mirror: nodes.jsonl drop={git_nodes_dropped}, edges.jsonl drop={git_edges_dropped}"
    )

    if commit:
        async with conn.transaction():
            await conn.execute(
                "DELETE FROM free_will.passage_citations WHERE kg_node_id = ANY($1::text[])",
                shells,
            )
            await conn.execute(
                "DELETE FROM free_will.kg_edges WHERE source = ANY($1::text[]) OR target = ANY($1::text[])",
                shells,
            )
            await conn.execute(
                "DELETE FROM free_will.kg_nodes WHERE node_id = ANY($1::text[])", shells
            )
        print(
            f"COMMITTED Phase B: -{cit_n} citations, -{edge_n} edges, -{len(shells)} nodes (DB) "
            f"+ git nodes -{git_nodes_dropped}, edges -{git_edges_dropped}."
        )
    else:
        print("[DRY-RUN] Phase B: no DB changes; git files NOT rewritten.")

    return {
        "db_citations": cit_n,
        "db_edges": edge_n,
        "db_nodes": len(shells),
        "git_nodes": git_nodes_dropped,
        "git_edges": git_edges_dropped,
    }


