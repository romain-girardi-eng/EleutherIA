async def _work_id(conn: asyncpg.Connection, canonical_id: str) -> str | None:
    wid: str | None = await conn.fetchval(
        "SELECT work_id::text FROM free_will.ancient_works WHERE canonical_id = $1",
        canonical_id,
    )
    return wid


async def _passage_id_for_ref(
    conn: asyncpg.Connection, work_id: str, ref: str
) -> str | None:
    pid: str | None = await conn.fetchval(
        "SELECT passage_id::text FROM free_will.passages WHERE work_id = $1::uuid AND canonical_ref = $2",
        work_id,
        ref,
    )
    return pid


async def _book_refs(
    conn: asyncpg.Connection, work_id: str, book: str
) -> list[tuple[str, str]]:
    rows = await conn.fetch(
        "SELECT passage_id::text AS pid, canonical_ref FROM free_will.passages "
        "WHERE work_id = $1::uuid AND canonical_ref LIKE $2 ORDER BY sequence_number",
        work_id,
        f"{book}.%",
    )
    return [(r["pid"], r["canonical_ref"]) for r in rows]


async def _shell_ids(conn: asyncpg.Connection) -> list[str]:
    rows = await conn.fetch(
        "SELECT node_id FROM free_will.kg_nodes "
        "WHERE node_id LIKE $1 OR node_id LIKE $2 ORDER BY node_id",
        *SHELL_LIKE,
    )
    return [r["node_id"] for r in rows]


# ---------------------------------------------------------------------------
# git mirror editing
# ---------------------------------------------------------------------------
def _git_node_id(obj: dict) -> str:
    return obj.get("id") or obj.get("node_id") or ""


def _git_edge_ends(obj: dict) -> tuple[str, str, str]:
    s = obj.get("source") or obj.get("source_id") or obj.get("source_node_id") or ""
    t = obj.get("target") or obj.get("target_id") or obj.get("target_node_id") or ""
    r = obj.get("relation") or obj.get("edge_type") or ""
    return s, t, r


def _remove_git_lines(
    path: Path, drop_predicate: Callable[[dict], bool], commit: bool
) -> int:
    """Rewrite a JSONL file dropping lines for which predicate(obj) is True.

    Returns count of dropped lines. Byte-for-byte preserves surviving lines
    (writes original line text, not a re-serialization) so unrelated rows are
    untouched. Atomic replace via .tmp.
    """
    kept: list[str] = []
    dropped = 0
    with path.open(encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            obj = json.loads(line)
            if drop_predicate(obj):
                dropped += 1
            else:
                kept.append(line if line.endswith("\n") else line + "\n")
    if commit and dropped:
        tmp = path.with_suffix(path.suffix + ".tmp")
        with tmp.open("w", encoding="utf-8") as f:
            f.writelines(kept)
        tmp.replace(path)
    return dropped


