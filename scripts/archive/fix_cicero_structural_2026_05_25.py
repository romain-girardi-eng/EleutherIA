# PHASE A
# ---------------------------------------------------------------------------
async def phase_a(conn: asyncpg.Connection, commit: bool, ts: str) -> dict:
    print("\n" + "=" * 70)
    print("PHASE A — re-ground arguments to genuine De Div / De Nat Deorum")
    print("=" * 70)

    # Resolve work_ids
    work_ids: dict[str, str] = {}
    for canon in (DIV_CANONICAL, NATDEOR_CANONICAL):
        wid = await _work_id(conn, canon)
        if not wid:
            raise SystemExit(f"Genuine work {canon} not found in ancient_works")
        work_ids[canon] = wid

    # Build the citation plan: (passage_id, ref, arg, confidence, note)
    plan: list[dict] = []
    missing: list[str] = []
    for arg, spec in REGROUND_PLAN.items():
        wid = work_ids[spec["work"]]
        if spec.get("refs") is None:
            # whole book
            refs_pids = await _book_refs(conn, wid, spec["book"])
        else:
            refs_pids = []
            for ref in spec["refs"]:
                pid = await _passage_id_for_ref(conn, wid, ref)
                if pid is None:
                    missing.append(
                        f"{arg}: {spec['work']} {ref} (genuine passage absent)"
                    )
                    continue
                refs_pids.append((pid, ref))
        for pid, ref in refs_pids:
            plan.append(
                {
                    "arg": arg,
                    "work": spec["work"],
                    "ref": ref,
                    "passage_id": pid,
                    "confidence": spec["confidence"],
                    "note": spec["note"],
                }
            )

    # Idempotency: which (arg, passage_id) primary_source citations already exist?
    existing_pairs: set[tuple[str, str]] = set()
    args_in_plan = sorted({p["arg"] for p in plan})
    if args_in_plan:
        rows = await conn.fetch(
            "SELECT kg_node_id, passage_id::text AS pid FROM free_will.passage_citations "
            "WHERE kg_node_id = ANY($1::text[]) AND citation_type = 'primary_source'",
            args_in_plan,
        )
        existing_pairs = {(r["kg_node_id"], r["pid"]) for r in rows}

    to_create = [p for p in plan if (p["arg"], p["passage_id"]) not in existing_pairs]
    already = len(plan) - len(to_create)

    # Stale bogus citation to delete (arg evidenced_by -> Topica passage)
    stale = await conn.fetch(
        "SELECT pc.citation_id::text AS cid, pc.citation_type, p.canonical_ref, w.canonical_id "
        "FROM free_will.passage_citations pc "
        "JOIN free_will.passages p ON p.passage_id = pc.passage_id "
        "JOIN free_will.ancient_works w ON w.work_id = p.work_id "
        "WHERE pc.kg_node_id = $1 AND w.canonical_id IN ($2, $3)",
        STALE_BOGUS_ARG_CITATION,
        TOPICA_CANONICAL,
        ORATOR_CANONICAL,
    )

    # Report
    per_arg: dict[str, int] = {}
    for p in to_create:
        per_arg[p["arg"]] = per_arg.get(p["arg"], 0) + 1
    print(f"Arguments to re-ground          : {len(REGROUND_PLAN)}")
    print(
        f"primary_source citations to add : {len(to_create)} (already present: {already})"
    )
    for arg in sorted(REGROUND_PLAN):
        spec = REGROUND_PLAN[arg]
        n = per_arg.get(arg, 0)
        sample = next((p["ref"] for p in to_create if p["arg"] == arg), "-")
        print(f"  {arg}")
        print(
            f"      work={spec['work'].rsplit('_', 2)[-2]}  new_cits={n}  e.g. ref {sample}  conf={spec['confidence']}"
        )
    print(f"\nArguments SKIPPED (no explicit Cicero locus): {len(SKIPPED_ARGS)}")
    for a, why in SKIPPED_ARGS.items():
        print(f"  {a}: {why}")
    if missing:
        print(f"\nLoci with NO genuine passage (skipped): {len(missing)}")
        for m in missing:
            print(f"  {m}")
    print(f"\nStale bogus arg-citations to delete: {len(stale)}")
    for s in stale:
        print(
            f"  {s['cid']} type={s['citation_type']} -> {s['canonical_id']} {s['canonical_ref']}"
        )

    snap = {
        "timestamp": ts,
        "phase": "A",
        "citations_to_create": to_create,
        "stale_bogus_deleted": [dict(s) for s in stale],
        "skipped_args": SKIPPED_ARGS,
        "missing_loci": missing,
    }
    (SNAPSHOT_DIR / "phase_a.json").write_text(
        json.dumps(snap, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    if commit:
        async with conn.transaction():
            for p in to_create:
                await conn.execute(
                    "INSERT INTO free_will.passage_citations "
                    "(passage_id, kg_node_id, citation_type, confidence, notes) "
                    "VALUES ($1::uuid, $2, 'primary_source', $3, $4)",
                    p["passage_id"],
                    p["arg"],
                    p["confidence"],
                    f"re-grounded {ts}: {p['note']} ref {p['ref']}",
                )
            for s in stale:
                await conn.execute(
                    "DELETE FROM free_will.passage_citations WHERE citation_id = $1::uuid",
                    s["cid"],
                )
        print(f"\nCOMMITTED Phase A: +{len(to_create)} citations, -{len(stale)} stale.")
    else:
        print("\n[DRY-RUN] Phase A: no DB changes.")

    return {
        "created": len(to_create),
        "already": already,
        "args": len(per_arg),
        "stale_deleted": len(stale),
        "missing": missing,
    }


