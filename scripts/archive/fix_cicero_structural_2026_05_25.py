"""Cicero structural fix: re-ground arguments, delete fake passage-shells + bogus works.

Background
----------
122 KG passage-shell nodes ``passage_cic_div_*`` (100) + ``passage_cic_nat_deor_*``
(22) were ingested from the WRONG corpus slots: Cicero *Topica* (phi042) and
*Orator* (phi041). Their stored text is Topica/Orator prose and the trailing "N"
is a Topica/Orator section index, NOT a genuine *De Divinatione* / *De Natura
Deorum* locus. They carry structural edges (122 ``authored_by`` to Cicero, 122
``part_of`` to the De Div / De Nat Deorum KG work nodes) and are referenced by
~11 Carneadean arguments via 49 ``cites_primary_source`` + 1 ``evidenced_by``
edges. Their ``passage_citations`` (type ``snapshot_passage_node``) point at the
Topica/Orator passages.

The genuine works are correctly ingested:
  - De Divinatione   urn_cts_latinlit_phi0474_phi053_lat  (refs 1.1 .. 2.150)
  - De Natura Deorum urn_cts_latinlit_phi0474_phi050_lat  (refs 1.1 .. 3.95)

Three phases (dry-run by default; --commit to mutate; --phase to select)
-----------------------------------------------------------------------
PHASE A — re-ground the arguments
  For each argument whose description names explicit De Div / De Nat Deorum loci
  (single sections AND ranges), create a ``passage_citations`` row linking the
  GENUINE corpus passage at that ref to the ARGUMENT node
  (citation_type='primary_source'). ZERO fabrication: only loci the argument
  explicitly states are used. Arguments naming no Cicero locus are skipped.
  Also deletes the one stale bogus Topica ``evidenced_by`` citation that
  argument_cicero_de_div_anti_mantike_amand1945 still carries (superseded by its
  genuine 2.21 primary_source citation).

PHASE B — delete the fake shells (everywhere)
  Delete the 122 shells' ``passage_citations`` rows, their ``kg_edges`` rows (all
  294 relations), and their ``kg_nodes`` rows in the DB; remove the same node
  lines from data/kg/nodes.jsonl and edge lines from data/kg/edges.jsonl.

PHASE C — drop the bogus Topica/Orator works
  After Phase B, confirm 0 remaining ``passage_citations`` on the phi042/phi041
  passages, then delete their passages + ancient_works rows. STOP if any citation
  remains.

Sync rule: KG git mirror (data/kg/*.jsonl) is edited DIRECTLY (the API exporter
lags); corpus snapshot (data/corpus/{passages,citations}.jsonl) is regenerated by
scripts.export_corpus_snapshot after this script.

Usage:
    .venv/bin/python -m scripts.fix_cicero_structural_2026_05_25 [--phase A|B|C|all] [--commit]

Dependencies: asyncpg (DATABASE_URL from .env). lxml not used here.
"""

