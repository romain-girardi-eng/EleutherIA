#
# Each argument -> (genuine_work_canonical, [explicit canonical_refs], confidence,
# provenance note). ONLY loci the argument explicitly names in its own
# description are listed (single sections expanded from ranges). Arguments that
# name no Cicero locus are intentionally absent (recorded in SKIPPED_ARGS).
# ---------------------------------------------------------------------------
def _expand(*parts: object) -> list[str]:
    """Expand book.section specs into canonical_refs.

    Accepts ints/strs for single sections ("2.97") and (book, start, end) tuples
    for inclusive ranges within one book ("2", 9, 72 -> 2.9 .. 2.72).
    """
    out: list[str] = []
    for p in parts:
        if isinstance(p, tuple):
            book, start, end = p
            out.extend(f"{book}.{s}" for s in range(start, end + 1))
        else:
            out.append(str(p))
    # dedupe preserving order
    seen: set[str] = set()
    deduped: list[str] = []
    for r in out:
        if r not in seen:
            seen.add(r)
            deduped.append(r)
    return deduped


